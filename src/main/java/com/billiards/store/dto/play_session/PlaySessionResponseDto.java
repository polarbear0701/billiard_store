package com.billiards.store.dto.play_session;

import java.time.LocalDateTime;

import com.billiards.store.common.enumerated.SessionStatus;

import io.swagger.v3.oas.annotations.media.Schema;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Schema(description = "A play session on a table")
public class PlaySessionResponseDto {
    @Schema(description = "Play session code, generated by the server", example = "SES000001")
    private String sessionCode;
    @Schema(description = "Code of the table being played", example = "TBL000001")
    private String tableCode;
    @Schema(description = "When play started (ISO-8601 date-time in the store's timezone)", example = "2026-10-19T18:30:00")
    private LocalDateTime startTime;
    @Schema(description = "When play ended (ISO-8601 date-time in the store's timezone); null while the session is running", example = "2026-10-19T20:00:00")
    private LocalDateTime endTime;
    @Schema(description = "Status of the session")
    private SessionStatus sessionStatus;
    @Schema(description = "When the record was created (ISO-8601 date-time in the store's timezone)", example = "2026-10-19T18:30:00")
    private LocalDateTime createdAt;
    @Schema(description = "When the record was last changed (ISO-8601 date-time in the store's timezone); null if never changed", example = "2026-10-19T19:00:00")
    private LocalDateTime updatedAt;
    @Schema(description = "Username that created the record (`SYSTEM` if done without a logged-in user)", example = "admin")
    private String createdBy;
    @Schema(description = "Username that last changed the record", example = "admin")
    private String updatedBy;
}
