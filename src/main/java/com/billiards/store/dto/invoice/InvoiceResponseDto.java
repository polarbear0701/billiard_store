package com.billiards.store.dto.invoice;

import java.math.BigDecimal;
import java.time.LocalDateTime;

import io.swagger.v3.oas.annotations.media.Schema;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Schema(description = "A bill for a play session")
public class InvoiceResponseDto {
    @Schema(description = "Invoice code, generated by the server", example = "INV000001")
    private String invoiceCode;
    @Schema(description = "Code of the billed session", example = "SES000001")
    private String sessionCode;
    @Schema(description = "Table rental fee in VND", example = "90000.00")
    private BigDecimal tableFee;
    @Schema(description = "Food and drink total in VND", example = "45000.00")
    private BigDecimal fnbFee;
    @Schema(description = "Total to pay in VND (table fee + food and drink)", example = "135000.00")
    private BigDecimal totalAmount;
    @Schema(description = "true once the invoice has been paid", example = "false")
    private boolean complete;
    @Schema(description = "When the invoice was paid (ISO-8601 date-time in the store's timezone); null while unpaid", example = "2026-10-19T20:05:00")
    private LocalDateTime paidAt;
    @Schema(description = "When the record was created (ISO-8601 date-time in the store's timezone)", example = "2026-10-19T18:30:00")
    private LocalDateTime createdAt;
    @Schema(description = "When the record was last changed (ISO-8601 date-time in the store's timezone); null if never changed", example = "2026-10-19T19:00:00")
    private LocalDateTime updatedAt;
    @Schema(description = "Username that created the record (`SYSTEM` if done without a logged-in user)", example = "admin")
    private String createdBy;
    @Schema(description = "Username that last changed the record", example = "admin")
    private String updatedBy;
}
