package com.billiards.store.dto.product;

import java.math.BigDecimal;
import java.time.LocalDateTime;

import io.swagger.v3.oas.annotations.media.Schema;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Schema(description = "A product in stock")
public class ProductResponseDto {
    @Schema(description = "Product code, generated by the server", example = "PRD000001")
    private String productCode;
    @Schema(description = "Product name", example = "Coca-Cola can")
    private String name;
    @Schema(description = "Units in stock", example = "24")
    private int quantity;
    @Schema(description = "Unit price in VND", example = "15000")
    private BigDecimal price;
    @Schema(description = "When the record was created (ISO-8601 date-time in the store's timezone)", example = "2026-10-19T18:30:00")
    private LocalDateTime createdAt;
    @Schema(description = "When the record was last changed (ISO-8601 date-time in the store's timezone); null if never changed", example = "2026-10-19T19:00:00")
    private LocalDateTime updatedAt;
    @Schema(description = "Username that created the record (`SYSTEM` if done without a logged-in user)", example = "admin")
    private String createdBy;
    @Schema(description = "Username that last changed the record", example = "admin")
    private String updatedBy;
}
